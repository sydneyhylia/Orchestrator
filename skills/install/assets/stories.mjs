// ---------- Reading

function parseFrontmatter(raw, file) {
  const m = lf(raw).match(/^---\n([\s\S]*?)\n?---\n?([\s\S]*)$/);
  if (!m) { errors.push(`${file}: missing frontmatter.`); return { data: {}, body: lf(raw) }; }
  const data = {};
  for (const line of m[1].split("\n")) {
    if (/^\s+-\s/.test(line)) { errors.push(`${file}: use inline lists in the frontmatter ([A, B]), not "- " lines.`); continue; }
    const kv = line.match(/^([\w_]+):\s*(.*?)\s*(\s#.*)?$/);
    if (!kv) continue;
    const unquote = (x) => x.trim().replace(/^(["'])(.*)\1$/, "$2");
    let v = unquote(kv[2]);
    if (v.startsWith("[") && v.endsWith("]")) v = v.slice(1, -1).split(",").map(unquote).filter(Boolean);
    else if (v === "true" || v === "false") v = v === "true";
    data[kv[1]] = v;
  }
  return { data, body: m[2] };
}

const asList = (v) => (Array.isArray(v) ? v : v ? [v] : []);
const sections = (body) => {
  const out = {};
  for (const part of body.split(/^## /m).slice(1)) {
    const nl = part.indexOf("\n");
    const head = (nl < 0 ? part : part.slice(0, nl)).trim();
    out[head.toLowerCase()] = nl < 0 ? "" : part.slice(nl + 1);
  }
  return out;
};
const section = (secs, key) => secs[L.sections[key].toLowerCase()];
const meaningful = (s) => (s ?? "").replace(/<!--[\s\S]*?-->/g, "").replace(/^\s*[-*]\s*$/gm, "").trim();

function parseCriteria(text, file, storyId) {
  if (!text) return [];
  const criteria = [];
  const M = L.markers;
  const known = new RegExp(`\\[((?:${[M.test, M.manual, M.unverified, M.unbuilt, M.failing].map(escape).join("|")})(?![\\p{L}\\p{N}]).*)\\]\\s*$`, "iu");
  for (const block of text.split(/^- /m).slice(1)) {
    const idMatch = block.match(/^\*\*([A-Z]{2,4}-\d{3}\.\d+)\*\*/);
    if (!idMatch) { errors.push(`${file}: criterion "${block.split("\n")[0].slice(0, 40)}" has no valid ID (**${storyId}.N**).`); continue; }
    const id = idMatch[1];
    if (!id.startsWith(storyId + ".")) errors.push(`${file}: criterion ${id} does not belong to ${storyId}.`);
    // The rule is the text before the first nested bullet; nested bullets are key examples.
    const head = block.split(/\n\s+[-*] /)[0].replace(/\s+/g, " ").trim();
    const examples = (block.match(/\n\s+[-*] /g) ?? []).length;
    const marker = head.match(known)?.[1].trim() ?? head.match(/\[([^\]]+)\]\s*$/)?.[1].trim() ?? null;
    criteria.push({ id, head, examples, ...classify(marker, file, id) });
  }
  return criteria;
}

function escape(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }

function classify(marker, file, id) {
  const M = L.markers;
  if (!marker) { errors.push(`${file}: criterion ${id} does not end with its verification marker in brackets.`); return { kind: "unverified" }; }
  const starts = (m) => new RegExp(`^${escape(m)}(?![\\p{L}\\p{N}])`, "iu").test(marker);
  if (starts(M.test)) {
    const ref = marker.match(new RegExp(`^${escape(M.test)}:\\s*(.+?)\\s*›\\s*"(.+)"$`, "i"));
    // A title made only of placeholders would match every test in the file.
    if (ref && !ref[2].replace(/%[sdifjo#%]/g, "").replace(/[\s\p{P}]/gu, "")) {
      errors.push(`${file}: criterion ${id} refers to a test title with no literal text ("${ref[2]}").`);
      return { kind: "unverified" };
    }
    return { kind: "test", ref: ref ? { file: ref[1].replace(/\\/g, "/"), title: ref[2] } : null };
  }
  if (starts(M.manual)) {
    // [manual YYYY-MM-DD, who]: a check by hand counts only with its date and the person who made it.
    if (!new RegExp(`^${escape(M.manual)}\\s+\\d{4}-\\d{2}-\\d{2},\\s*\\S.*$`, "iu").test(marker)) {
      errors.push(`${file}: criterion ${id} has [${marker}]. Write [${M.manual} YYYY-MM-DD, who].`);
      return { kind: "unverified" };
    }
    return { kind: "manual" };
  }
  if (new RegExp(`^${escape(M.unverified)}$`, "i").test(marker)) return { kind: "unverified" };
  if (new RegExp(`^${escape(M.unbuilt)}$`, "i").test(marker)) return { kind: "unbuilt" };
  if (starts(M.failing)) return { kind: "failing", reason: marker.replace(new RegExp(`^${escape(M.failing)}:\\s*`, "i"), "") };
  errors.push(`${file}: criterion ${id} has an unknown marker: [${marker}].`);
  return { kind: "unverified" };
}

function readDir(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return readDir(p);
    return e.name.endsWith(".md") ? [p] : [];
  });
}

const rel = (p) => path.relative(DIR, p).split(path.sep).join("/");
const activities = readJson(path.join(DIR, "activities.json"));
const byCode = new Map(activities.map((a) => [a.code, a]));

const decisions = new Map();
for (const file of readDir(path.join(DIR, "decisions"))) {
  const { data } = parseFrontmatter(readFileSync(file, "utf8"), rel(file));
  if (!data.id) continue;
  decisions.set(data.id, { ...data, file: rel(file), open: !DECISION_CLOSED.test(String(data.status ?? "")) });
}

const stories = [];
const seen = new Set();
for (const file of readDir(path.join(DIR, "stories"))) {
  const f = rel(file);
  const { data, body } = parseFrontmatter(readFileSync(file, "utf8"), f);
  const id = data.id;
  if (!/^[A-Z]{2,4}-\d{3}$/.test(id ?? "")) { errors.push(`${f}: invalid id "${id}".`); continue; }
  if (seen.has(id)) errors.push(`${f}: id ${id} is repeated.`);
  seen.add(id);
  const code = id.split("-")[0];
  const act = byCode.get(code);
  if (!act) errors.push(`${f}: activity code ${code} is not in activities.json.`);
  else {
    if (!f.startsWith(`stories/${act.folder}/`)) errors.push(`${f}: must live in stories/${act.folder}/.`);
    if (data.activity && data.activity !== act.name) errors.push(`${f}: activity "${data.activity}" does not match activities.json ("${act.name}").`);
  }
  if (!path.basename(file).startsWith(id + "-")) errors.push(`${f}: file name must start with ${id}-.`);
  if (!RELEASES.includes(data.release)) errors.push(`${f}: unknown release "${data.release}". Known: ${RELEASES.join(", ")}.`);
  if (PERSONAS && data.persona && !PERSONAS.includes(data.persona)) errors.push(`${f}: persona "${data.persona}" is not in stories.config.json personas.`);
  const blockedBy = asList(data.blocked_by);
  for (const d of blockedBy) if (!decisions.has(d)) errors.push(`${f}: decision ${d} does not exist.`);
  const secs = sections(body);
  stories.push({
    id, title: data.title, code, release: data.release, persona: data.persona,
    tags: asList(data.tags), blockedBy, dependsOn: asList(data.depends_on), discarded: data.discarded === true,
    screens: asList(data.screens), secs, criteria: parseCriteria(section(secs, "criteria"), f, id), file: f,
  });
}
stories.sort((a, b) => a.id.localeCompare(b.id));
const storyIds = new Set(stories.map((s) => s.id));
for (const s of stories) for (const d of s.dependsOn) if (!storyIds.has(d)) errors.push(`${s.file}: depends_on ${d} does not exist.`);

