const cwd = path.resolve(ROOT, T?.cwd ?? ".");
const norm = (p) => path.relative(cwd, path.resolve(cwd, p)).split(path.sep).join("/");

function parseReport(file, junit) {
  const raw = lf(readFileSync(file, "utf8"));
  if (junit) {
    const cases = [];
    // Attribute values may hold a raw '>' (Node's reporter does not escape it): skip quoted strings whole.
    for (const m of raw.matchAll(/<testcase\b((?:[^>"]|"[^"]*")*?)(\/>|>([\s\S]*?)<\/testcase>)/g)) {
      const xml = (v) => v.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
      const attr = (n) => xml(m[1].match(new RegExp(`(?:^|\\s)${n}="([^"]*)"`))?.[1] ?? "");
      const inner = m[3] ?? "";
      const status = /<(failure|error)\b/.test(inner) ? "failed" : /<skipped\b/.test(inner) ? "skipped" : "passed";
      cases.push({ file: norm(attr("file") || attr("classname").replace(/\./g, "/")), title: attr("name"), status });
    }
    return cases;
  }
  let report;
  try { report = JSON.parse(raw); } catch { errors.push(`${path.basename(file)} is not valid JSON: run with --tests again.`); return []; }
  return report.testResults.flatMap((f) => f.assertionResults.map((t) => ({ file: norm(f.name), title: t.title, status: t.status })));
}

function loadResults() {
  // tests.reports: extra report files (e.g. e2e) merged with the main one; the format is read from the content.
  const extra = asList(T?.reports).map((p) => path.resolve(cwd, p)).filter((p) => existsSync(p));
  const last = existsSync(LAST) ? readJson(LAST) : [];
  if (!existsSync(RESULTS) && !extra.length && !last.length) return null;
  const cases = [
    ...(existsSync(RESULTS) ? parseReport(RESULTS, (T?.format ?? "jest-json") === "junit") : []),
    ...extra.flatMap((p) => parseReport(p, readFileSync(p, "utf8").trimStart().startsWith("<"))),
  ];
  // A test absent from the reports, or skipped, did not run this time: keep its last known result.
  // A report cannot tell a test skipped by its own code from one filtered out, so both count as not run.
  const ran = (t) => t.status === "passed" || t.status === "failed";
  const key = (t) => `${t.file}\0${t.title}`;
  const ranNow = new Set(cases.filter(ran).map(key));
  const skippedNow = new Set(cases.filter((t) => !ran(t)).map(key));
  const known = new Set(last.map(key));
  return [
    ...cases.filter((t) => ran(t) || !known.has(key(t))),
    ...last.filter((t) => !ranNow.has(key(t))).map((t) => (skippedNow.has(key(t)) ? { ...t, notRun: true } : t)),
  ];
}
const tests = loadResults();

const sameFile = (a, b) => { const [x, y] = a.length >= b.length ? [a, b] : [b, a]; return x === y || x.endsWith("/" + y); };

function testResult(c) {
  if (!tests) return "noResults";
  const byId = tests.filter((t) => t.title.startsWith(`[${c.id}]`));
  // Parameterised tests (it.each) report %s, %d... substituted: treat them as wildcards.
  const pattern = c.ref && new RegExp("^" + c.ref.title.split(/%[sdifjo#%]/).map(escape).join(".*") + "$");
  const matches = byId.length ? byId : c.ref
    ? tests.filter((t) => sameFile(c.ref.file, t.file)).filter((t) => pattern.test(t.title))
    : [];
  if (!matches.length) return "notFound";
  c.notRun = matches.some((t) => t.notRun);
  if (matches.some((t) => t.status === "failed")) return "fail";
  return matches.every((t) => t.status === "passed") ? "pass" : "skipped";
}

// ---------- Status of each story

for (const s of stories) {
  for (const c of s.criteria) {
    if (c.kind !== "test") continue;
    c.result = testResult(c);
    // No result now nor before: the test has not run yet, or the marker names a test that does not exist.
    if (c.result === "notFound") warnings.push(`${s.file}: no test result for ${c.id} (not run yet, or no such test).`);
  }
  const kinds = s.criteria.map((c) => (c.kind === "test" ? ({ pass: "ok", fail: "failing" }[c.result] ?? "unverified") : c.kind === "manual" ? "ok" : c.kind));
  const openDecisions = s.blockedBy.filter((d) => decisions.get(d)?.open);
  if (!s.criteria.length && !s.discarded) errors.push(`${s.file}: has no acceptance criteria.`);
  if (s.discarded && !meaningful(section(s.secs, "discardReason"))) errors.push(`${s.file}: discarded without a "${L.sections.discardReason}" section.`);
  s.status =
    s.discarded ? "discarded"
    : openDecisions.length ? "blocked"
    : kinds.includes("failing") ? "failing"
    : kinds.length && kinds.every((k) => k === "unbuilt") ? "pending"
    : kinds.includes("unbuilt") ? "partial"
    : kinds.includes("unverified") ? "unverified"
    : !kinds.length ? "pending"
    : "works";
}

// ---------- Ready check (only what an agent cannot resolve alone)

function readyProblems(s) {
  const p = [];
  const w = [];
  if (s.discarded) p.push("story is discarded");
  if (s.blockedBy.some((d) => decisions.get(d)?.open)) p.push(`blocked by an open decision: ${s.blockedBy.join(", ")}`);
  const storyText = (section(s.secs, "story") ?? "").toLowerCase();
  if (!L.storyKeywords.every((k) => new RegExp(`(^|[^\\p{L}])${escape(k)}([^\\p{L}]|$)`, "iu").test(storyText))) w.push(`"${L.sections.story}" does not follow the ${L.storyKeywords.join(" / ")} shape`);
  if (!meaningful(section(s.secs, "outOfScope"))) p.push(`"${L.sections.outOfScope}" is missing or empty`);
  if (meaningful(section(s.secs, "openQuestions"))) p.push(`"${L.sections.openQuestions}" is not empty`);
  if (!meaningful(section(s.secs, "verification"))) p.push(`"${L.sections.verification}" is missing or empty`);
  for (const d of s.dependsOn) { const dep = stories.find((x) => x.id === d); if (dep && dep.status !== "works") w.push(`depends on ${d}, which is ${dep.status}`); }
  if (s.criteria.length > 6) w.push(`${s.criteria.length} criteria: consider splitting the story`);
  const words = (list, txt) => list.filter((v) => new RegExp(`(^|[^\\p{L}])${escape(v)}([^\\p{L}]|$)`, "iu").test(txt));
  for (const c of s.criteria) {
    const v = words(L.vague, c.head);
    if (v.length) w.push(`${c.id}: vague words (${v.join(", ")}): say what is measured`);
    const h = words(L.hedges, c.head);
    if (h.length) p.push(`${c.id}: hedged obligation (${h.join(", ")}): state what the system does`);
  }
  return { problems: p, warnings: w };
}

// ---------- Outputs

const emoji = (e) => L.statuses[e].split(" ")[0];
const screens = (s) => s.screens.map((u, i) => ` [🖼${s.screens.length > 1 ? i + 1 : ""}](${u})`).join("");
const link = (s) => `${emoji(s.status)} [${s.id}](${s.file}) ${s.title}${screens(s)}`;

if (flag("--summary")) {
  // Compact state for the start of a session: only what needs attention.
  const counts = STATUS_ORDER.map((e) => `${L.statuses[e]} ${stories.filter((s) => s.status === e).length}`).join(", ");
  const active = stories.filter((s) => ["failing", "partial", "unverified", "blocked"].includes(s.status));
  const lines = [`${stories.length} stories: ${counts}`, ""];
  for (const s of active) {
    const bad = s.criteria.filter((c) => c.kind === "failing" || c.result === "fail").map((c) => c.id);
    lines.push(`${emoji(s.status)} ${s.id} ${s.title}${bad.length ? ` (failing: ${bad.join(", ")})` : ""}${s.status === "blocked" ? ` (blocked by ${s.blockedBy.join(", ")})` : ""}`);
  }
  const open = [...decisions.values()].filter((d) => d.open);
  if (open.length) lines.push("", `Open decisions: ${open.map((d) => `${d.id} ${d.title}`).join("; ")}`);
  if (errors.length) lines.push("", `${errors.length} validation problem(s). Run without --summary to list them.`);
  finish(lines.join("\n"), errors.length ? 1 : 0);
}

if (flag("--json")) {
  finish(JSON.stringify({
    stories: stories.map((st) => { const { secs, ...s } = st; return { ...s, ready: readyProblems(st) }; }),
    decisions: [...decisions.values()], errors, warnings,
  }, null, 2), errors.length ? 1 : 0);
}

if (flag("--ready")) {
  const ids = listAfter("--ready");
  let failed = false;
  const lines = [];
  for (const id of ids) {
    const s = stories.find((x) => x.id === id);
    if (!s) { lines.push(`${id}: story not found.`); failed = true; continue; }
    const r = readyProblems(s);
    const own = errors.filter((e) => e.startsWith(s.file + ":"));
    const bad = [...own, ...r.problems];
    lines.push(`${id} ${bad.length ? "NOT READY" : "READY"}`);
    for (const e of bad) lines.push(`  ✗ ${e}`);
    for (const x of r.warnings) lines.push(`  ! ${x}`);
    if (bad.length) failed = true;
  }
  finish(lines.join("\n"), failed ? 1 : 0);
}

if (flag("--pr")) {
  const s = stories.find((x) => x.id === listAfter("--pr")[0]);
  if (!s) { console.error("Story not found."); process.exit(2); }
  const res = (c) => c.kind === "test" ? ({ pass: "✅", fail: "❌" }[c.result] ?? "⚠️") : c.kind === "manual" ? "✅" : c.kind === "failing" ? "❌" : "⚠️";
  finish([`## ${s.id} ${s.title}`, "", `${L.statuses[s.status]}, [${s.file}](${path.relative(ROOT, path.join(DIR, s.file)).split(path.sep).join("/")})`, "",
    ...s.criteria.map((c) => `- ${res(c)} **${c.id}** ${c.head.replace(/^\*\*[^*]+\*\*\s*/, "")}`)].join("\n"), 0);
}

const active = stories.filter((s) => s.status !== "discarded");
const main = active.filter((s) => s.release === MAIN_RELEASE);
const ok = main.filter((s) => s.status === "works").length;
const pct = main.length ? Math.round((ok / main.length) * 100) : 0;
const uncovered = activities.filter((a) => !main.some((s) => s.code === a.code && s.status === "works"));
const openDecisions = [...decisions.values()].filter((d) => d.open);
const blockedBy = (d) => stories.filter((s) => s.blockedBy.includes(d));
const X = L.text;

const out = [];
out.push(`# ${X.title}`, "", `> ${fill(X.generated, { script: SCRIPT })}`, "");
out.push(fill(X.progress, { release: MAIN_RELEASE, ok, total: main.length, pct }), "");
out.push(tests ? X.testsIn : fill(X.testsOut, { script: SCRIPT }), "");
out.push(`| ${X.status} | ${MAIN_RELEASE} | ${X.total} |`, "|---|---|---|");
for (const e of STATUS_ORDER) {
  const t = stories.filter((s) => s.status === e).length;
  if (t) out.push(`| ${L.statuses[e]} | ${main.filter((s) => s.status === e).length} | ${t} |`);
}
out.push("", `**${fill(X.uncovered, { release: MAIN_RELEASE })}:** ${uncovered.length ? uncovered.map((a) => a.name).join(", ") : X.none}`, "");
if (openDecisions.length) {
  out.push(`**${X.blocking}:**`, "", ...openDecisions.map((d) => `- [${d.id}](${d.file}) ${d.title} (${blockedBy(d.id).length})`), "");
}
for (const lane of config.lanes ?? L.lanes) {
  const acts = activities.filter((a) => (a.lane ?? "journey") === lane.id);
  if (!acts.length) continue;
  out.push(`## ${lane.title}`, "");
  for (const a of acts) {
    const hs = stories.filter((s) => s.code === a.code);
    out.push(`### ${a.code} ${a.name}`, "", ...(a.purpose ? [`_${a.purpose}_`, ""] : []));
    if (!hs.length) { out.push(X.noStories, ""); continue; }
    for (const r of RELEASES) {
      const list = hs.filter((s) => s.release === r && s.status !== "discarded");
      if (list.length) out.push(`**${r}**`, "", ...list.map((s) => `- ${link(s)}`), "");
    }
    const desc = hs.filter((s) => s.status === "discarded");
    if (desc.length) out.push(`**${X.discardedGroup}**`, "", ...desc.map((s) => `- ${link(s)}`), "");
  }
}
if (decisions.size) {
  out.push(`## ${X.decisions}`, "", `| ID | ${X.decision} | ${X.status} | ${X.blocks} |`, "|---|---|---|---|");
  for (const d of decisions.values()) {
    const b = blockedBy(d.id).map((s) => `[${s.id}](${s.file})`).join(", ") || "—";
    out.push(`| [${d.id}](${d.file}) | ${d.title} | ${d.status} | ${b} |`);
  }
  out.push("");
}
out.push(`## ${X.legend}`, "", ...STATUS_ORDER.map((e) => `- ${L.statuses[e]}`), "");
const md = out.join("\n");

if (flag("--check")) {
  // The main release must be green: a failing criterion fails the check, not only a stale map.
  // A skipped test did not run this time: it warns, and the criterion keeps its last known result.
  for (const s of main) for (const c of s.criteria) {
    if (c.kind === "failing") errors.push(`${s.file}: ${c.id} is marked failing in ${MAIN_RELEASE}.`);
    else if (c.result === "fail") errors.push(`${s.file}: the test for ${c.id} fails.`);
    else if (c.result === "skipped" || c.notRun) warnings.push(`${s.file}: the test for ${c.id} is skipped${c.notRun ? " (last known result kept)" : ""}.`);
  }
}

if (errors.length) { console.error(`\n${errors.length} problem(s):`); for (const e of errors) console.error("  - " + e); }
if (warnings.length) { console.error(`\n${warnings.length} warning(s):`); for (const w of warnings) console.error("  - " + w); }
if (runnerCode) console.error(`\nThe test command exited with code ${runnerCode}.`);

if (flag("--check")) {
  const current = existsSync(MAP) ? lf(readFileSync(MAP, "utf8")) : "";
  if (current !== md) { console.error(`\nmap.md is stale: run \`node ${SCRIPT}\`.`); process.exit(1); }
  if (errors.length || runnerCode) process.exit(1);
  console.log("map.md is up to date.");
} else {
  writeFileSync(MAP, md);
  if (tests) writeFileSync(LAST, JSON.stringify(tests.filter((t) => t.status === "passed" || t.status === "failed").map(({ file, title, status }) => ({ file, title, status })), null, 1) + "\n");
  console.log(`map.md written: ${stories.length} stories, ${MAIN_RELEASE} ${ok}/${main.length} (${pct} %).`);
  if (errors.length) process.exit(1);
  if (runnerCode) process.exit(runnerCode);
}
